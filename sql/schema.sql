-- 1) 기념일 (D-day / 캘린더에 표시)
create table if not exists anniversaries (
  id          bigint generated by default as identity primary key,
  title       text not null,
  date        date not null,
  emoji       text default '💗',
  yearly      boolean default false,            -- 매년 반복(생일 등)
  created_at  timestamptz default now()
);

-- 2) 버킷리스트 (카테고리: travel/buy/eat/do)
create table if not exists bucket_items (
  id          bigint generated by default as identity primary key,
  category    text not null default 'do',       -- travel | buy | eat | do
  title       text not null,
  done        boolean default false,
  done_at     timestamptz,
  created_by  text,
  created_at  timestamptz default now()
);

-- 3) 한줄일기 / 편지
create table if not exists diary_entries (
  id          bigint generated by default as identity primary key,
  author      text,                             -- 작성자 이메일
  mood        text default '🙂',
  content     text not null,
  entry_date  date default current_date,
  created_at  timestamptz default now()
);

-- 4) 오늘의 기분 (사람당 한 줄, upsert)
create table if not exists statuses (
  user_email  text primary key,
  mood        text default '😊',
  message     text default '',
  updated_at  timestamptz default now()
);

-- 5) 콕 찌르기 (보고싶어! 알림)
create table if not exists pokes (
  id          bigint generated by default as identity primary key,
  from_email  text,
  message     text default '보고싶어! 💗',
  created_at  timestamptz default now()
);

-- 6) 추억 사진첩
create table if not exists photos (
  id          bigint generated by default as identity primary key,
  url         text not null,                    -- Storage public URL
  caption     text default '',
  taken_date  date,
  created_by  text,
  created_at  timestamptz default now()
);

-- 7) 우리 발자취 타임라인
create table if not exists footprints (
  id          bigint generated by default as identity primary key,
  title       text not null,
  place       text default '',
  note        text default '',
  emoji       text default '📍',
  date        date,
  created_at  timestamptz default now()
);

-- 8) 데이트 룰렛 항목 (food / activity)
create table if not exists roulette_options (
  id          bigint generated by default as identity primary key,
  category    text not null default 'activity', -- food | activity
  text        text not null,
  created_at  timestamptz default now()
);

-- ============================================================
--  v2 추가 컬럼 (재실행 안전 — 이미 있으면 무시)
-- ============================================================
alter table anniversaries add column if not exists repeat text default 'none'; -- none|weekly|monthly|yearly
alter table bucket_items  add column if not exists subcat   text;
alter table bucket_items  add column if not exists country  text;   -- 국내|국외
alter table bucket_items  add column if not exists region   text;
alter table bucket_items  add column if not exists want_date date;
alter table bucket_items  add column if not exists url      text;
alter table photos        add column if not exists title    text;
alter table footprints    add column if not exists photo_url text;

-- 기존 yearly=true 데이터를 repeat='yearly' 로 한 번 정리
update anniversaries set repeat = 'yearly' where yearly = true and (repeat is null or repeat = 'none');

-- ============================================================
--  RLS (Row Level Security)
--  로그인한 사용자(우리 둘)만 모든 작업 허용
-- ============================================================
do $$
declare t text;
begin
  foreach t in array array[
    'anniversaries','bucket_items','diary_entries','statuses',
    'pokes','photos','footprints','roulette_options'
  ]
  loop
    execute format('alter table %I enable row level security;', t);
    execute format('drop policy if exists "couple_all" on %I;', t);
    execute format(
      'create policy "couple_all" on %I for all to authenticated using (true) with check (true);', t
    );
  end loop;
end $$;

-- ============================================================
--  실시간(Realtime) 켜기 — 상대가 수정하면 바로 반영/알림
-- ============================================================
do $$
declare t text;
begin
  foreach t in array array[
    'anniversaries','bucket_items','diary_entries','statuses',
    'pokes','photos','footprints','roulette_options'
  ]
  loop
    begin
      execute format('alter publication supabase_realtime add table %I;', t);
    exception when duplicate_object then null;
    end;
  end loop;
end $$;

