-- 테이블이 비어있을 때만 기본 항목 추가 (재실행 시 중복 방지)
insert into roulette_options (category, text)
select v.category, v.text from (values
  ('food','떡볶이'),('food','초밥'),('food','파스타'),('food','마라탕'),
  ('food','삼겹살'),('food','치킨'),('food','국밥'),('food','햄버거'),
  ('activity','영화보기'),('activity','카페 가기'),('activity','드라이브'),
  ('activity','집에서 뒹굴기'),('activity','산책'),('activity','보드게임'),
  ('activity','전시회'),('activity','노래방')
) as v(category, text)
where not exists (select 1 from roulette_options);

-- ============================================================
--  사진 저장용 Storage 버킷
--  (대시보드 Storage 에서 'photos' 버킷을 Public 으로 만들어도 됩니다)
-- ============================================================
-- 권한 문제로 실패해도 전체가 롤백되지 않도록 감쌈
do $$
begin
  insert into storage.buckets (id, name, public) values ('photos','photos', true) on conflict (id) do nothing;
exception when others then null;
end $$;

do $$
begin
  drop policy if exists "photos_read" on storage.objects;
  create policy "photos_read"   on storage.objects for select using (bucket_id = 'photos');
  drop policy if exists "photos_write" on storage.objects;
  create policy "photos_write"  on storage.objects for insert to authenticated with check (bucket_id = 'photos');
  drop policy if exists "photos_delete" on storage.objects;
  create policy "photos_delete" on storage.objects for delete to authenticated using (bucket_id = 'photos');
exception when others then null;
end $$;
